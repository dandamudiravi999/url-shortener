CREATE TABLE short_url (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(32)   NOT NULL,
    original_url     VARCHAR(2048) NOT NULL,
    custom_alias     BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP     NOT NULL,
    expires_at       TIMESTAMP,
    deleted_at       TIMESTAMP,
    click_count      BIGINT        NOT NULL DEFAULT 0,
    last_accessed_at TIMESTAMP,
    version          BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uk_short_url_code UNIQUE (code)
);

CREATE INDEX idx_short_url_original_url ON short_url (original_url);

CREATE TABLE click_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_url_id BIGINT       NOT NULL,
    occurred_at  TIMESTAMP    NOT NULL,
    referrer     VARCHAR(512),
    user_agent   VARCHAR(512),
    CONSTRAINT fk_click_event_short_url FOREIGN KEY (short_url_id) REFERENCES short_url (id) ON DELETE CASCADE
);

CREATE INDEX idx_click_event_url_time ON click_event (short_url_id, occurred_at);
